-- UUID migration, phase 1 (additive, non-breaking): add a uuid column to every
-- table getting a UUID primary key, backfilled with a fresh uuid per existing row
-- (a volatile DEFAULT on ADD COLUMN forces Postgres to evaluate it per row, not
-- once for the whole table). Then add a matching uuid column to every foreign key
-- field still typed Int/BigInt, backfilled by joining the old value to the
-- referenced table's new uuid id. FK fields already uuid-typed (referencing the
-- three tables that were already on UUID) are untouched. Old int columns are left
-- alone here; the finalization migration renames the new ones into place once
-- application code is confirmed reading/writing uuid ids.

-- lead_scores: no surrogate key today (composite PK on pesuser_name+dept) — give it one.
ALTER TABLE "lead_scores" ADD COLUMN "id_uuid" UUID NOT NULL DEFAULT gen_random_uuid();

-- subscriptions: reuse the existing (empty) old_uuid_id column as the new id,
-- rather than adding yet another column — this is what it was seemingly meant for.
UPDATE "subscriptions" SET "old_uuid_id" = gen_random_uuid() WHERE "old_uuid_id" IS NULL;
ALTER TABLE "subscriptions" ALTER COLUMN "old_uuid_id" SET NOT NULL;

